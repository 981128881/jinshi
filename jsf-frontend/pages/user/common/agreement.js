export function getAgreementContent(type, meta = {}) {
	const options = {
		shopName: meta.shopName || '金石菜牌齐市店',
		servicePhone: meta.servicePhone || '400-888-8888'
	}
	if (type === 'privacy') return buildPrivacyPolicy(options)
	return buildServiceAgreement(options)
}
